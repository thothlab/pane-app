//! Root CA management: generation via rcgen, persistence (public PEM in
//! storage + private key in OS keychain), export to PEM/DER/QR/mobileconfig,
//! leaf-cert issuance on the fly with an LRU cache.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use anyhow::{anyhow, Context, Result};
use base64::Engine as _;
use pane_ipc::{CaCertificateDto, CaExportResult};
use pane_storage::Storage;
use parking_lot::RwLock;
use rcgen::{
    BasicConstraints, CertificateParams, DistinguishedName, DnType, IsCa, KeyPair, KeyUsagePurpose,
    PKCS_ECDSA_P256_SHA256,
};
use sha2::{Digest, Sha256};
use time::OffsetDateTime;
use uuid::Uuid;

const KEYRING_SERVICE: &str = "tech.thothlab.pane";
const KEYRING_USER_PREFIX: &str = "ca-key-";

#[derive(Clone)]
pub struct CaMaterial {
    pub id: Uuid,
    pub cert_pem: String,
    pub key_pem: String,
}

/// Why the CA could not be opened.
#[derive(Debug, thiserror::Error)]
pub enum CaOpenError {
    /// The OS keychain refused or failed (denied prompt, locked keychain).
    /// The key is probably still there, so this is retryable, not lost.
    #[error("the OS keychain did not return the private key of CA {id}: {reason}")]
    KeyUnreadable { id: Uuid, reason: String },
    /// The key is gone, and this process may not issue a replacement.
    #[error("the private key of CA {id} is in neither the OS keychain nor {}", path.display())]
    KeyAbsent { id: Uuid, path: PathBuf },
    #[error(transparent)]
    Other(#[from] anyhow::Error),
}

struct CaStoreInner {
    material: CaMaterial,
    dto: CaCertificateDto,
}

pub struct CaStore {
    storage: Arc<Storage>,
    inner: RwLock<CaStoreInner>,
    /// Where the on-disk key fallback lives. Previously every path was
    /// derived from a hardcoded `ProjectDirs` lookup, so `open_or_init`'s
    /// `data_dir` parameter was ignored and no test could be pointed at a
    /// tempdir without scribbling into the developer's real data directory.
    data_dir: PathBuf,
}

impl CaStore {
    /// Load the current CA, or issue one if the database has none.
    ///
    /// `owner` says whether this process owns the data directory. Only the
    /// owner may replace a CA whose key is gone: a guest (the CLI with no
    /// instance running) holds no lock, and swapping the CA under an app that
    /// starts a moment later would leave the two disagreeing about the key.
    pub fn open_or_init(
        data_dir: &Path,
        storage: &Arc<Storage>,
        owner: bool,
    ) -> Result<Self, CaOpenError> {
        if let Some(existing) = storage.current_ca_record()? {
            // Auto-migrate: CA generated by <= 0.1.7 used Ed25519, which
            // Android's conscrypt rejects in the trust store ("couldn't
            // open certificate file" from CertInstaller). If we see an
            // Ed25519 SPKI OID in the DER, transparently rotate to ECDSA
            // so the user doesn't have to know about this gotcha.
            if is_ed25519_pem(&existing.pem) {
                tracing::info!("rotating legacy Ed25519 CA to ECDSA P-256 (Android compatibility)");
                let store = Self::rotate_existing(storage.clone(), existing.id, data_dir)?;
                return Ok(store);
            }
            let key_pem = match read_keyring(&existing.id, data_dir)? {
                KeyLookup::Found(key_pem) => key_pem,
                KeyLookup::Absent if owner => {
                    let store = Self::rotate_existing(storage.clone(), existing.id, data_dir)?;
                    tracing::warn!(
                        old_ca = %existing.id,
                        new_ca = %store.material().id,
                        key_file = %fallback_path(&existing.id, data_dir).display(),
                        "CA private key is in neither the OS keychain nor the key file; \
                         issued a new CA, devices must reinstall it"
                    );
                    return Ok(store);
                }
                KeyLookup::Absent => {
                    return Err(CaOpenError::KeyAbsent {
                        id: existing.id,
                        path: fallback_path(&existing.id, data_dir),
                    })
                }
                // Never rotated away: a refused prompt or a locked keychain
                // passes, and a new CA would break every paired device.
                KeyLookup::Unreadable(reason) => {
                    return Err(CaOpenError::KeyUnreadable {
                        id: existing.id,
                        reason,
                    })
                }
            };
            let material = CaMaterial {
                id: existing.id,
                cert_pem: existing.pem.clone(),
                key_pem,
            };
            return Ok(Self {
                storage: storage.clone(),
                inner: RwLock::new(CaStoreInner {
                    material,
                    dto: existing.into_dto(),
                }),
                data_dir: data_dir.to_path_buf(),
            });
        }

        let fresh = generate_root("Pane Root CA")?;
        let sha = sha256_pem(&fresh.cert_pem);
        let id = Uuid::new_v4();
        write_keyring(&id, &fresh.key_pem, data_dir)?;
        storage.insert_ca(
            id,
            &fresh.cert_pem,
            &sha,
            "CN=Pane Root CA",
            fresh.not_before,
            fresh.not_after,
        )?;
        let dto = CaCertificateDto {
            id,
            serial: short_serial(&sha),
            sha256_fp: sha,
            subject: "CN=Pane Root CA".into(),
            valid_from: fresh.not_before.to_string(),
            valid_to: fresh.not_after.to_string(),
            revoked_at: None,
        };
        let material = CaMaterial {
            id,
            cert_pem: fresh.cert_pem,
            key_pem: fresh.key_pem,
        };
        Ok(Self {
            storage: storage.clone(),
            inner: RwLock::new(CaStoreInner { material, dto }),
            data_dir: data_dir.to_path_buf(),
        })
    }

    /// Same shape as `rotate()` but takes an explicit old CA id and is
    /// callable before the store is constructed (used for the boot-time
    /// Ed25519 → ECDSA migration).
    fn rotate_existing(storage: Arc<Storage>, old_id: Uuid, data_dir: &Path) -> Result<Self> {
        let fresh = generate_root("Pane Root CA")?;
        let sha = sha256_pem(&fresh.cert_pem);
        let id = Uuid::new_v4();
        write_keyring(&id, &fresh.key_pem, data_dir)?;
        storage.revoke_ca(old_id)?;
        storage.insert_ca(
            id,
            &fresh.cert_pem,
            &sha,
            "CN=Pane Root CA",
            fresh.not_before,
            fresh.not_after,
        )?;
        let dto = CaCertificateDto {
            id,
            serial: short_serial(&sha),
            sha256_fp: sha,
            subject: "CN=Pane Root CA".into(),
            valid_from: fresh.not_before.to_string(),
            valid_to: fresh.not_after.to_string(),
            revoked_at: None,
        };
        let material = CaMaterial {
            id,
            cert_pem: fresh.cert_pem,
            key_pem: fresh.key_pem,
        };
        Ok(Self {
            storage,
            inner: RwLock::new(CaStoreInner { material, dto }),
            data_dir: data_dir.to_path_buf(),
        })
    }

    pub fn material(&self) -> CaMaterial {
        self.inner.read().material.clone()
    }

    pub fn current_dto(&self) -> Result<CaCertificateDto> {
        Ok(self.inner.read().dto.clone())
    }

    pub fn rotate(&self) -> Result<CaCertificateDto> {
        let fresh = generate_root("Pane Root CA")?;
        let sha = sha256_pem(&fresh.cert_pem);
        let id = Uuid::new_v4();
        write_keyring(&id, &fresh.key_pem, &self.data_dir)?;
        // Mark old revoked, insert new.
        let old_id = self.inner.read().material.id;
        self.storage.revoke_ca(old_id)?;
        self.storage.insert_ca(
            id,
            &fresh.cert_pem,
            &sha,
            "CN=Pane Root CA",
            fresh.not_before,
            fresh.not_after,
        )?;
        let dto = CaCertificateDto {
            id,
            serial: short_serial(&sha),
            sha256_fp: sha,
            subject: "CN=Pane Root CA".into(),
            valid_from: fresh.not_before.to_string(),
            valid_to: fresh.not_after.to_string(),
            revoked_at: None,
        };
        let material = CaMaterial {
            id,
            cert_pem: fresh.cert_pem,
            key_pem: fresh.key_pem,
        };
        *self.inner.write() = CaStoreInner {
            material,
            dto: dto.clone(),
        };
        Ok(dto)
    }

    pub fn export(&self, format: &str) -> Result<CaExportResult> {
        let pem = self.inner.read().material.cert_pem.clone();
        match format {
            "pem" => Ok(CaExportResult {
                format: "pem".into(),
                data_base64: Some(base64::engine::general_purpose::STANDARD.encode(pem)),
                path: None,
                mime: "application/x-pem-file".into(),
            }),
            "der" => {
                let der = pem_to_der(&pem)?;
                Ok(CaExportResult {
                    format: "der".into(),
                    data_base64: Some(base64::engine::general_purpose::STANDARD.encode(der)),
                    path: None,
                    mime: "application/pkix-cert".into(),
                })
            }
            "qr" => {
                let url = format!(
                    "data:application/x-pem-file;base64,{}",
                    base64::engine::general_purpose::STANDARD.encode(&pem)
                );
                let qr = qrcode::QrCode::new(url.as_bytes())?;
                let svg = qr.render::<qrcode::render::svg::Color>().build();
                Ok(CaExportResult {
                    format: "qr".into(),
                    data_base64: Some(base64::engine::general_purpose::STANDARD.encode(svg)),
                    path: None,
                    mime: "image/svg+xml".into(),
                })
            }
            "mobileconfig" => {
                let xml = pane_mobileconfig::build_ca_profile(&pem)?;
                Ok(CaExportResult {
                    format: "mobileconfig".into(),
                    data_base64: Some(base64::engine::general_purpose::STANDARD.encode(xml)),
                    path: None,
                    mime: "application/x-apple-aspen-config".into(),
                })
            }
            other => Err(anyhow!("unsupported export format: {other}")),
        }
    }
}

struct GeneratedRoot {
    cert_pem: String,
    key_pem: String,
    not_before: OffsetDateTime,
    not_after: OffsetDateTime,
}

fn generate_root(common_name: &str) -> Result<GeneratedRoot> {
    let mut params = CertificateParams::default();
    let mut dn = DistinguishedName::new();
    dn.push(DnType::CommonName, common_name);
    dn.push(DnType::OrganizationName, "Pane");
    params.distinguished_name = dn;
    params.is_ca = IsCa::Ca(BasicConstraints::Unconstrained);
    params.key_usages = vec![
        KeyUsagePurpose::KeyCertSign,
        KeyUsagePurpose::CrlSign,
        KeyUsagePurpose::DigitalSignature,
    ];
    let now = OffsetDateTime::now_utc();
    let not_before = now;
    let not_after = now + time::Duration::days(365 * 3);
    params.not_before = not_before;
    params.not_after = not_after;

    // ECDSA P-256, not Ed25519: Android's conscrypt (and many older Java
    // TrustManagers) doesn't accept Ed25519 in the user/system trust store —
    // CertInstaller silently rejects with "couldn't open certificate file".
    // ECDSA P-256 is supported everywhere Android 4.x+ and small enough to
    // keep our PEM under a kilobyte.
    let key_pair = KeyPair::generate_for(&PKCS_ECDSA_P256_SHA256)?;
    let cert = params.self_signed(&key_pair)?;

    Ok(GeneratedRoot {
        cert_pem: cert.pem(),
        key_pem: key_pair.serialize_pem(),
        not_before,
        not_after,
    })
}

fn sha256_pem(pem: &str) -> String {
    let der = match pem_to_der(pem) {
        Ok(d) => d,
        Err(_) => return String::new(),
    };
    let mut hasher = Sha256::new();
    hasher.update(&der);
    hex::encode(hasher.finalize())
}

fn short_serial(sha: &str) -> String {
    sha.chars().take(16).collect()
}

/// Detect whether a PEM-encoded certificate uses an Ed25519 public key.
///
/// We look for the SPKI AlgorithmIdentifier OID 1.3.101.112 in the DER,
/// which BER-encodes to the byte sequence `06 03 2B 65 70` (tag=OID,
/// length=3, bytes). Scanning the whole DER is sufficient — the OID
/// isn't ambiguous with other fields at that arity for the rcgen-generated
/// certificates we care about, and a false positive only triggers a
/// harmless extra rotation at boot.
fn is_ed25519_pem(pem: &str) -> bool {
    let der = match pem_to_der(pem) {
        Ok(d) => d,
        Err(_) => return false,
    };
    der.windows(5).any(|w| w == [0x06, 0x03, 0x2B, 0x65, 0x70])
}

fn pem_to_der(pem: &str) -> Result<Vec<u8>> {
    let payload = pem
        .lines()
        .filter(|l| !l.starts_with("-----"))
        .collect::<String>();
    Ok(base64::engine::general_purpose::STANDARD.decode(payload)?)
}

fn keyring_entry(id: &Uuid) -> keyring::Result<keyring::Entry> {
    let user = format!("{KEYRING_USER_PREFIX}{id}");
    keyring::Entry::new(KEYRING_SERVICE, &user)
}

/// Whether to bypass the OS keyring and store the CA key on disk.
///
/// Keychain ACLs are bound to the requesting binary's code signature. Unsigned
/// `cargo` dev builds change hash on every rebuild, so "Always allow" never
/// sticks — the user is re-prompted on each launch. In debug builds we route
/// through a file in the data dir instead. The `PANE_KEYCHAIN` env var forces
/// the keyring path when set (handy when testing the production code path).
fn use_file_storage() -> bool {
    if std::env::var_os("PANE_KEYCHAIN").is_some() {
        return false;
    }
    cfg!(debug_assertions)
}

fn write_keyring(id: &Uuid, key_pem: &str, data_dir: &Path) -> Result<()> {
    if use_file_storage() {
        return write_file(id, key_pem, data_dir);
    }
    match keyring_entry(id).and_then(|e| e.set_password(key_pem)) {
        Ok(()) => Ok(()),
        Err(e) => {
            tracing::warn!(error = %e, "keyring write failed — falling back to on-disk file");
            write_file(id, key_pem, data_dir)
        }
    }
}

/// Where the search for a CA's private key ended up.
enum KeyLookup {
    Found(String),
    /// The keychain has no such entry and there is no key file: the key is
    /// gone, and only a new CA gets the proxy running again.
    Absent,
    /// The keychain refused or failed, so the key may well still be there.
    Unreadable(String),
}

fn read_keyring(id: &Uuid, data_dir: &Path) -> Result<KeyLookup> {
    if use_file_storage() {
        if let Some(v) = read_key_file(id, data_dir)? {
            return Ok(KeyLookup::Found(v));
        }
        // Migration: a CA generated by a previous build stored its key in the
        // OS keyring. Read once (one final prompt), persist to file, never
        // prompt again.
        return match keyring_entry(id).and_then(|e| e.get_password()) {
            Ok(v) => {
                write_file(id, &v, data_dir)?;
                tracing::info!(ca = %id, "migrated CA key from OS keyring to data-dir file");
                Ok(KeyLookup::Found(v))
            }
            Err(e) => Ok(classify_key_lookup(id, e, None)),
        };
    }
    match keyring_entry(id).and_then(|e| e.get_password()) {
        Ok(v) => Ok(KeyLookup::Found(v)),
        Err(e) => Ok(classify_key_lookup(id, e, read_key_file(id, data_dir)?)),
    }
}

fn classify_key_lookup(id: &Uuid, keychain: keyring::Error, file: Option<String>) -> KeyLookup {
    // NoEntry is routine in release: the key went to the file because the
    // keychain write failed back then. Anything else is worth seeing in the log.
    if !matches!(keychain, keyring::Error::NoEntry) {
        tracing::warn!(ca = %id, error = %keychain, "OS keychain did not return the CA key");
    }
    match (keychain, file) {
        (_, Some(v)) => KeyLookup::Found(v),
        (keyring::Error::NoEntry, None) => KeyLookup::Absent,
        (e, None) => KeyLookup::Unreadable(e.to_string()),
    }
}

fn read_key_file(id: &Uuid, data_dir: &Path) -> Result<Option<String>> {
    let path = fallback_path(id, data_dir);
    match std::fs::read_to_string(&path) {
        Ok(v) => Ok(Some(v)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e).with_context(|| format!("reading {}", path.display())),
    }
}

fn write_file(id: &Uuid, key_pem: &str, data_dir: &Path) -> Result<()> {
    let path = fallback_path(id, data_dir);
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&path, key_pem)?;
    // 0600 — readable only by the owning user.
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perm = std::fs::metadata(&path)?.permissions();
        perm.set_mode(0o600);
        std::fs::set_permissions(&path, perm)?;
    }
    Ok(())
}

fn fallback_path(id: &Uuid, data_dir: &Path) -> PathBuf {
    data_dir.join("ca-keys").join(format!("{id}.pem"))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The mock keychain answers NoEntry for any key it was never given,
    /// which is what macOS says for a deleted item. Without it the lookup
    /// would reach the real OS keychain, and a CI runner with no secret
    /// service reports a failure instead.
    fn open(dir: &Path, owner: bool) -> (Arc<Storage>, Result<CaStore, CaOpenError>) {
        keyring::set_default_credential_builder(keyring::mock::default_credential_builder());
        let storage = Arc::new(Storage::open(dir).unwrap());
        let store = CaStore::open_or_init(dir, &storage, owner);
        (storage, store)
    }

    fn lose_key(dir: &Path) -> Uuid {
        let (_, store) = open(dir, true);
        let id = store.unwrap().material().id;
        std::fs::remove_file(fallback_path(&id, dir)).unwrap();
        id
    }

    #[test]
    fn owner_issues_a_new_ca_when_the_key_is_gone() {
        let dir = tempfile::tempdir().unwrap();
        let lost = lose_key(dir.path());

        let (storage, store) = open(dir.path(), true);

        let fresh = store.expect("a lost key must not stop the app").material();
        assert_ne!(fresh.id, lost);
        assert_eq!(storage.current_ca_record().unwrap().unwrap().id, fresh.id);
        assert!(fallback_path(&fresh.id, dir.path()).exists());
    }

    #[test]
    fn guest_refuses_and_leaves_the_ca_alone() {
        let dir = tempfile::tempdir().unwrap();
        let lost = lose_key(dir.path());

        let (storage, store) = open(dir.path(), false);

        assert!(matches!(store, Err(CaOpenError::KeyAbsent { id, .. }) if id == lost));
        assert_eq!(storage.current_ca_record().unwrap().unwrap().id, lost);
    }

    #[test]
    fn a_refusing_keychain_is_not_a_lost_key() {
        let id = Uuid::new_v4();
        let refused = || keyring::Error::PlatformFailure("User canceled the operation.".into());

        assert!(matches!(
            classify_key_lookup(&id, refused(), None),
            KeyLookup::Unreadable(reason) if reason.contains("User canceled")
        ));
        assert!(matches!(
            classify_key_lookup(&id, keyring::Error::NoEntry, None),
            KeyLookup::Absent
        ));
        assert!(matches!(
            classify_key_lookup(&id, refused(), Some("pem".into())),
            KeyLookup::Found(v) if v == "pem"
        ));
    }
}
